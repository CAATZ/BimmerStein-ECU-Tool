        movb RL4,0xFCA0
        cmpb RL4,#5
        jmpa cc_UGT,rejected_snapshot
        mov r4,0xFF50
        and r4,#0x4F00
        cmp r4,#0x4300
        jmpa cc_NE,rejected_snapshot
        mov r4,0xFF46
        and r4,#0x00CF
        cmp r4,#0x0041
        jmpa cc_NE,rejected_snapshot
        cmp r3,#0
        jmpa cc_EQ,rejected_snapshot
